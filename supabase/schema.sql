CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, username TEXT NOT NULL UNIQUE,
 password TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('admin','user')),
 sector TEXT DEFAULT '', active INTEGER NOT NULL DEFAULT 1,
  terms_accepted_at TEXT DEFAULT NULL
);
CREATE TABLE IF NOT EXISTS parts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE, name TEXT NOT NULL, category TEXT NOT NULL,
 location TEXT NOT NULL, quantity INTEGER NOT NULL DEFAULT 0 CHECK(quantity >= 0),
 min_quantity INTEGER NOT NULL DEFAULT 0 CHECK(min_quantity >= 0),
 unit TEXT NOT NULL DEFAULT 'un', supplier TEXT DEFAULT '',
 unit_price DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(unit_price >= 0),
 sector TEXT DEFAULT '', entry_date TEXT DEFAULT '', description TEXT DEFAULT '',
 deleted_at TEXT, deleted_by BIGINT
);
CREATE TABLE IF NOT EXISTS requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 part_id BIGINT NOT NULL REFERENCES parts(id),
 quantity INTEGER NOT NULL CHECK(quantity > 0),
 comment TEXT DEFAULT '', status TEXT NOT NULL DEFAULT 'pendente',
 admin_note TEXT DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 part_id BIGINT REFERENCES parts(id), user_id BIGINT REFERENCES users(id),
 type TEXT NOT NULL, quantity INTEGER NOT NULL CHECK(quantity > 0),
 note TEXT DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS signup_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, username TEXT NOT NULL, password TEXT NOT NULL,
 sector TEXT DEFAULT '', reason TEXT DEFAULT '',
 status TEXT NOT NULL DEFAULT 'pendente', admin_note TEXT DEFAULT '',
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
